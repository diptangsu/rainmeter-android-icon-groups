local OPEN_DURATION = 0.16
local CLOSE_DURATION = 0.12
local HOVER_IN_DURATION = 0.09
local HOVER_OUT_DURATION = 0.13

-- Visible closed-folder geometry inside FolderTemplate.inc (skin-local pixels)
local ICON_CENTER_X = 56
local ICON_CENTER_Y = 48
local ICON_RIGHT_EDGE = 86
local ICON_TOP_GAP_Y = 8
local DEFAULT_PANEL_X = 18
local DEFAULT_PANEL_Y = 104
local MAX_MONITORS = 16

local floor = math.floor
local ceil = math.ceil
local min = math.min
local max = math.max
