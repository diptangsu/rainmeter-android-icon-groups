local function LoadMonitorMetrics()
    local resPath = SKIN:GetVariable('@')
    if not resPath or resPath == '' then return nil end
    local ok, metrics = pcall(dofile, resPath .. 'MonitorMetrics.lua')
    if ok and type(metrics) == 'table' and type(metrics.monitors) == 'table' then
        return metrics
    end
    return nil
end

function Initialize()
    isOpen = false
    animState = "idle"
    animStartTime = 0
    animStartProgress = 0
    animProgress = 0
    openLeft = false
    openUp = false
    selectedIdx = -1

    hoveredIdx = -1
    hoverAlpha = 0
    hoverTarget = 0
    hoverStartTime = 0
    hoverStartAlpha = 0
    lastHoverAlpha = -1

    savedOrigX = nil
    savedOrigY = nil
    didMove = false
    pendingRestore = false

    cachedStyle = (SKIN:GetVariable('AnimStyle') or 'ExpandCollapse'):gsub('%s+', '')
    cachedPanelW = tonumber(SKIN:GetVariable('PanelWidth')) or 448
    cachedPanelH = tonumber(SKIN:GetVariable('PanelHeight')) or 146
    cachedPanelX = DEFAULT_PANEL_X
    cachedPanelY = DEFAULT_PANEL_Y

    -- Precomputed skin-local monitor clamp bounds for the active popup animation
    cachedMinLocalX = 2
    cachedMaxLocalRight = 99999
    cachedMinLocalY = 2
    cachedMaxLocalBottom = 99999

    -- Cache static grid layout metrics once per skin load/refresh
    cachedCols = tonumber(SKIN:GetVariable('GridCols')) or 4
    cachedCellW = tonumber(SKIN:GetVariable('CellW')) or 104
    cachedCellH = tonumber(SKIN:GetVariable('CellH')) or 98
    cachedPadX = tonumber(SKIN:GetVariable('PadX')) or 16
    cachedPadY = tonumber(SKIN:GetVariable('PadY')) or 48
    cachedIsCompact = (cachedCellW <= 90)
    cachedIconSize = cachedIsCompact and 34 or 40
    cachedLabelOffset = cachedIsCompact and 38 or 45

    -- Load Windows per-monitor DPI metadata snapshot (if generated by FolderManager.ps1)
    monitorMetrics = LoadMonitorMetrics()

    lastScale = -1
    lastAlpha = -1
    lastShiftX = -9999
    lastShiftY = -9999
    lastMatrix = ""

    SKIN:Bang('[!KeepOnScreen 0][!Draggable 1][!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle]')
end

function TogglePanel()
    if isOpen and animState ~= "closing" then
        ClosePanel()
    else
        OpenPanel()
    end
end

local function GetTileBoxSize(idx)
    local boxW = cachedCellW - 6
    local hitbox = SKIN:GetMeter('AppHitbox_' .. idx)
    if hitbox then
        local h = hitbox:GetH()
        if h and h > 0 then
            return boxW, h
        end
    end

    local boxH = cachedIsCompact and 72 or 88
    local labelMeter = SKIN:GetMeter('AppLabel_' .. idx)
    if labelMeter and not cachedIsCompact then
        local textLen = #(labelMeter:GetOption('Text') or '')
        if textLen <= 13 then
            boxH = 74
        elseif textLen <= 26 then
            boxH = 88
        else
            boxH = 96
        end
    end
    return boxW, boxH
end

function RestoreIcon(idx)
    if idx == nil or idx < 0 then return end
    local col = idx % cachedCols
    local row = floor(idx / cachedCols)

    local relIconX = cachedPadX + (col * cachedCellW) + floor(cachedCellW / 2) - floor(cachedIconSize / 2)
    local relIconY = cachedPadY + (row * cachedCellH)
    local relLabelY = relIconY + cachedLabelOffset

    local iconName = 'AppIcon_' .. idx
    local labelName = 'AppLabel_' .. idx

    -- Use #*Var*# so Rainmeter keeps literal #PanelX#/#PanelY# while TransformationMatrix handles scaling
    SKIN:Bang(
        '[!SetOption ' .. iconName .. ' X "(#*PanelX*# + ' .. relIconX .. ')"]' ..
        '[!SetOption ' .. iconName .. ' Y "(#*PanelY*# + ' .. relIconY .. ')"]' ..
        '[!SetOption ' .. iconName .. ' W "' .. cachedIconSize .. '"]' ..
        '[!SetOption ' .. iconName .. ' H "' .. cachedIconSize .. '"]' ..
        '[!SetOption ' .. labelName .. ' Y "(#*PanelY*# + ' .. relLabelY .. ')"]' ..
        '[!SetOption ' .. labelName .. ' FontWeight "400"]' ..
        '[!UpdateMeter ' .. iconName .. '][!UpdateMeter ' .. labelName .. ']'
    )
end

function ResetHover()
    hoveredIdx = -1
    hoverAlpha = 0
    hoverTarget = 0
    lastHoverAlpha = 0
    SKIN:Bang('[!SetVariable HoverAlpha 0][!HideMeter HoverHighlight][!UpdateMeter HoverHighlight]')
end

function HoverApp(idx)
    if not isOpen or animState ~= "idle" then return end
    idx = tonumber(idx) or -1
    if idx < 0 or idx == selectedIdx then
        if hoveredIdx >= 0 then UnhoverApp(hoveredIdx) end
        return
    end

    local col = idx % cachedCols
    local row = floor(idx / cachedCols)
    local baseIconY = cachedPadY + (row * cachedCellH)
    local hoverW, hoverH = GetTileBoxSize(idx)
    local relBoxX = cachedPadX + (col * cachedCellW) + 3
    local relBoxY = baseIconY - 6

    local bangs = {}
    if hoveredIdx ~= idx then
        hoveredIdx = idx
        bangs[#bangs + 1] =
            '[!SetVariable HoverX ' .. relBoxX .. ']' ..
            '[!SetVariable HoverY ' .. relBoxY .. ']' ..
            '[!SetVariable HoverW ' .. hoverW .. ']' ..
            '[!SetVariable HoverH ' .. hoverH .. ']' ..
            '[!ShowMeter HoverHighlight][!UpdateMeter HoverHighlight][!Redraw]'
    end

    hoverTarget = 1
    hoverStartAlpha = hoverAlpha
    hoverStartTime = clock()
    bangs[#bangs + 1] = '[!SetOption MeasureToggle UpdateDivider 1][!UpdateMeasure MeasureToggle]'
    SKIN:Bang(concat(bangs))
end

function UnhoverApp(idx)
    idx = tonumber(idx) or -1
    if hoveredIdx ~= idx then return end

    hoverTarget = 0
    hoverStartAlpha = hoverAlpha
    hoverStartTime = clock()
    SKIN:Bang('[!SetOption MeasureToggle UpdateDivider 1][!UpdateMeasure MeasureToggle]')
end

function SelectApp(idx)
    if not isOpen or animState ~= "idle" then return end
    idx = tonumber(idx) or -1
    if idx < 0 then
        ClearSelection()
        return
    end

    if selectedIdx >= 0 and selectedIdx ~= idx then
        RestoreIcon(selectedIdx)
    end

    selectedIdx = idx
    local col = idx % cachedCols
    local row = floor(idx / cachedCols)

    local baseIconX = cachedPadX + (col * cachedCellW) + floor(cachedCellW / 2) - floor(cachedIconSize / 2)
    local baseIconY = cachedPadY + (row * cachedCellH)
    local expIconX = baseIconX - 3
    local expIconY = baseIconY - 3
    local expIconSize = cachedIconSize + 6
    local expLabelY = baseIconY + cachedLabelOffset + 3

    local iconName = 'AppIcon_' .. idx
    local labelName = 'AppLabel_' .. idx
    local selW, selH = GetTileBoxSize(idx)
    local relBoxX = cachedPadX + (col * cachedCellW) + 3
    local relBoxY = baseIconY - 6

    local hoverClearBang = ''
    if hoveredIdx == idx then
        hoveredIdx = -1
        hoverAlpha = 0
        hoverTarget = 0
        lastHoverAlpha = 0
        hoverClearBang = '[!SetVariable HoverAlpha 0][!HideMeter HoverHighlight][!UpdateMeter HoverHighlight]'
    end

    SKIN:Bang(
        hoverClearBang ..
        '[!SetOption ' .. iconName .. ' X "(#*PanelX*# + ' .. expIconX .. ')"]' ..
        '[!SetOption ' .. iconName .. ' Y "(#*PanelY*# + ' .. expIconY .. ')"]' ..
        '[!SetOption ' .. iconName .. ' W "' .. expIconSize .. '"]' ..
        '[!SetOption ' .. iconName .. ' H "' .. expIconSize .. '"]' ..
        '[!SetOption ' .. labelName .. ' Y "(#*PanelY*# + ' .. expLabelY .. ')"]' ..
        '[!SetOption ' .. labelName .. ' FontWeight "600"]' ..
        '[!SetVariable SelW ' .. selW .. ']' ..
        '[!SetVariable SelH ' .. selH .. ']' ..
        '[!SetOption SelectionHighlight X "(#*PanelX*# + ' .. relBoxX .. ')"]' ..
        '[!SetOption SelectionHighlight Y "(#*PanelY*# + ' .. relBoxY .. ')"]' ..
        '[!ShowMeter SelectionHighlight]' ..
        '[!UpdateMeter ' .. iconName .. '][!UpdateMeter ' .. labelName .. '][!UpdateMeter SelectionHighlight][!Redraw]'
    )
end

function ClearSelection()
    if selectedIdx >= 0 then
        RestoreIcon(selectedIdx)
        selectedIdx = -1
    end
    SKIN:Bang('[!HideMeter SelectionHighlight][!UpdateMeter SelectionHighlight][!Redraw]')
end

function ApplyAnimFrame(p, skipRedraw)
    local style = cachedStyle
    local inv = 1 - p
    local ease = 1 - (inv * inv * inv)

    local scale = 1
    local alpha = floor(255 * ease + 0.5)
    local shiftX = 0
    local shiftY = 0

    if style == 'ExpandCollapse' then
        scale = 0.20 + (0.80 * ease)
        shiftX = openLeft and floor((1 - scale) * (cachedPanelW - 38)) or floor((1 - scale) * 20)
        shiftY = openUp and floor((1 - scale) * cachedPanelH) or floor(-(1 - scale) * 28)
    elseif style == 'ElasticBounce' then
        local pm1 = p - 1
        local backEase = 1 + 2.4 * (pm1 * pm1 * pm1) + 1.4 * (pm1 * pm1)
        scale = 0.20 + (0.80 * backEase)
        if scale < 0.15 then scale = 0.15 end
        local a = p * 1.8
        alpha = (a >= 1) and 255 or floor(255 * a + 0.5)
        shiftX = openLeft and floor((1 - scale) * (cachedPanelW - 38)) or floor((1 - scale) * 20)
        shiftY = openUp and floor((1 - scale) * cachedPanelH) or floor(-(1 - scale) * 28)
    elseif style == 'SubtlePop' then
        scale = 0.88 + (0.12 * ease)
        local a = p * 1.5
        alpha = (a >= 1) and 255 or floor(255 * a + 0.5)
        shiftX = floor((1 - scale) * cachedPanelW * 0.5)
        shiftY = floor((1 - scale) * cachedPanelH * 0.5)
    elseif style == 'Settle' then
        scale = 1.06 - (0.06 * ease)
        shiftX = floor((1 - scale) * cachedPanelW * 0.5)
        shiftY = floor((1 - scale) * cachedPanelH * 0.5)
    elseif style == 'VerticalBounce' then
        local pm1 = p - 1
        local backEase = 1 + 2.7 * (pm1 * pm1 * pm1) + 1.7 * (pm1 * pm1)
        local dist = floor((1 - backEase) * 42)
        local a = p * 1.8
        alpha = (a >= 1) and 255 or floor(255 * a + 0.5)
        shiftY = openUp and dist or -dist
    elseif style == 'Snap' then
        local a = p * 2.0
        alpha = (a >= 1) and 255 or floor(255 * a + 0.5)
        local nudge = floor((1 - ease) * 10)
        shiftY = openUp and nudge or -nudge
    elseif style == 'Slide' then
        local dist = floor((1 - ease) * 75)
        shiftX = openLeft and dist or -floor(dist * 0.35)
        shiftY = openUp and dist or -dist
    elseif style == 'Fade' then
        alpha = floor(255 * p + 0.5)
    else -- 'None'
        alpha = (p >= 0.5) and 255 or 0
    end

    -- Clamp alpha and round scale to 3 decimals to avoid micro-updates
    if alpha < 0 then alpha = 0 elseif alpha > 255 then alpha = 255 end
    scale = floor(scale * 1000 + 0.5) / 1000

    -- Clamp every animation frame strictly inside both skin origin (>= 2) and active monitor work-area
    local curW = cachedPanelW * scale
    local curH = cachedPanelH * scale
    local leftX = cachedPanelX + shiftX
    local topY = cachedPanelY + shiftY

    if (leftX + curW) > cachedMaxLocalRight then
        leftX = floor(cachedMaxLocalRight - curW)
    end
    if leftX < cachedMinLocalX then
        leftX = cachedMinLocalX
    end
    shiftX = floor(leftX - cachedPanelX)

    if (topY + curH) > cachedMaxLocalBottom then
        topY = floor(cachedMaxLocalBottom - curH)
    end
    if topY < cachedMinLocalY then
        topY = cachedMinLocalY
    end
    shiftY = floor(topY - cachedPanelY)

    -- Shared 2D affine matrix around (cachedPanelX, cachedPanelY) for icons & text meters
    local tx = floor((cachedPanelX * (1 - scale) + shiftX) * 100 + 0.5) / 100
    local ty = floor((cachedPanelY * (1 - scale) + shiftY) * 100 + 0.5) / 100
    if abs(tx) < 0.005 then tx = 0 end
    if abs(ty) < 0.005 then ty = 0 end
    local matrix = scale .. ';0;0;' .. scale .. ';' .. tx .. ';' .. ty

    local bangs = {}
    if scale ~= lastScale then
        lastScale = scale
        bangs[#bangs + 1] = '[!SetVariable AnimScale ' .. scale .. ']'
    end
    if alpha ~= lastAlpha then
        lastAlpha = alpha
        bangs[#bangs + 1] = '[!SetVariable AnimAlpha ' .. alpha .. ']'
    end
    if shiftX ~= lastShiftX then
        lastShiftX = shiftX
        bangs[#bangs + 1] = '[!SetVariable AnimShiftX ' .. shiftX .. ']'
    end
    if shiftY ~= lastShiftY then
        lastShiftY = shiftY
        bangs[#bangs + 1] = '[!SetVariable AnimShiftY ' .. shiftY .. ']'
    end
    if matrix ~= lastMatrix then
        lastMatrix = matrix
        bangs[#bangs + 1] = '[!SetVariable PanelMatrix "' .. matrix .. '"]'
    end

    if #bangs > 0 then
        if not skipRedraw then
            bangs[#bangs + 1] = '[!UpdateMeterGroup PanelContent][!Redraw]'
        end
        SKIN:Bang(concat(bangs))
    end
end

function Update()
    if pendingRestore then
        pendingRestore = false
        local moveBang = ''
        if savedOrigX ~= nil and savedOrigY ~= nil then
            moveBang = '[!KeepOnScreen 0][!Move ' .. savedOrigX .. ' ' .. savedOrigY .. ']'
        end
        didMove = false
        SKIN:Bang(moveBang .. '[!Draggable 1][!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle][!Redraw]')
        return
    end

    if animState ~= "idle" then
        local elapsed = clock() - animStartTime
        if animState == "opening" then
            local p = animStartProgress + (elapsed / OPEN_DURATION)
            if p >= 1 then
                animProgress = 1
                animState = "idle"
                ApplyAnimFrame(1, true)
                SKIN:Bang(
                    '[!ShowMeterGroup PanelHitboxes]' ..
                    '[!UpdateMeterGroup PanelContent][!UpdateMeterGroup PanelHitboxes]' ..
                    '[!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle][!Redraw]'
                )
                return
            end
            animProgress = p
            ApplyAnimFrame(p, false)
        elseif animState == "closing" then
            local p = animStartProgress - (elapsed / CLOSE_DURATION)
            if p <= 0 then
                animProgress = 0
                animState = "idle"
                FinishClose()
                return
            end
            animProgress = p
            ApplyAnimFrame(p, false)
        end
        return
    end

    -- Smooth Windows Start-style hover fade when panel is idle
    if hoverAlpha ~= hoverTarget then
        local elapsed = clock() - hoverStartTime
        local nextAlpha = hoverTarget
        if hoverTarget > hoverStartAlpha then
            local t = min(1, elapsed / HOVER_IN_DURATION)
            local inv = 1 - t
            nextAlpha = hoverStartAlpha + (1 - hoverStartAlpha) * (1 - inv * inv)
        else
            local t = min(1, elapsed / HOVER_OUT_DURATION)
            nextAlpha = hoverStartAlpha * (1 - t)
        end

        hoverAlpha = floor(nextAlpha * 1000 + 0.5) / 1000
        if abs(hoverAlpha - hoverTarget) < 0.01 then
            hoverAlpha = hoverTarget
        end

        local bangs = {}
        local needHoverRedraw = false
        if hoverAlpha ~= lastHoverAlpha then
            lastHoverAlpha = hoverAlpha
            bangs[#bangs + 1] = '[!SetVariable HoverAlpha ' .. hoverAlpha .. ']'
            needHoverRedraw = true
        end

        if hoverAlpha == hoverTarget then
            if hoverTarget == 0 then
                hoveredIdx = -1
                bangs[#bangs + 1] = '[!HideMeter HoverHighlight]'
                needHoverRedraw = true
            end
            bangs[#bangs + 1] = '[!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle]'
        end

        if needHoverRedraw then
            bangs[#bangs + 1] = '[!UpdateMeter HoverHighlight][!Redraw]'
        end

        if #bangs > 0 then
            SKIN:Bang(concat(bangs))
        end
    else
        SKIN:Bang('[!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle]')
    end
end

local function Sign(v)
    if v > 4 then return 1 elseif v < -4 then return -1 else return 0 end
end

local function SnapScale(s)
    if s < 0.4 or s > 2.6 then return 1.0 end
    if abs(s - 1.0) <= 0.03 then return 1.0 end
    return s
end

local function EnumerateRainmeterMonitors()
    local primSX = tonumber(SKIN:ReplaceVariables('#SCREENAREAX#')) or 0
    local primSY = tonumber(SKIN:ReplaceVariables('#SCREENAREAY#')) or 0
    local primSW = tonumber(SKIN:ReplaceVariables('#SCREENAREAWIDTH#')) or 1920
    local primSH = tonumber(SKIN:ReplaceVariables('#SCREENAREAHEIGHT#')) or 1080
    local primWX = tonumber(SKIN:ReplaceVariables('#WORKAREAX#')) or primSX
    local primWY = tonumber(SKIN:ReplaceVariables('#WORKAREAY#')) or primSY
    local primWW = tonumber(SKIN:ReplaceVariables('#WORKAREAWIDTH#')) or primSW
    local primWH = tonumber(SKIN:ReplaceVariables('#WORKAREAHEIGHT#')) or primSH

    local list = {}
    local primaryRm = nil

    for i = 1, MAX_MONITORS do
        local sw = tonumber(SKIN:ReplaceVariables('#SCREENAREAWIDTH@' .. i .. '#'))
        local sh = tonumber(SKIN:ReplaceVariables('#SCREENAREAHEIGHT@' .. i .. '#'))
        if not sw or not sh or sw <= 0 or sh <= 0 then
            break
        end
        local sx = tonumber(SKIN:ReplaceVariables('#SCREENAREAX@' .. i .. '#')) or 0
        local sy = tonumber(SKIN:ReplaceVariables('#SCREENAREAY@' .. i .. '#')) or 0
        local wx = tonumber(SKIN:ReplaceVariables('#WORKAREAX@' .. i .. '#')) or sx
        local wy = tonumber(SKIN:ReplaceVariables('#WORKAREAY@' .. i .. '#')) or sy
        local ww = tonumber(SKIN:ReplaceVariables('#WORKAREAWIDTH@' .. i .. '#')) or sw
        local wh = tonumber(SKIN:ReplaceVariables('#WORKAREAHEIGHT@' .. i .. '#')) or sh

        local isPrimary = (sx == primSX and sy == primSY and sw == primSW and sh == primSH)
        local mon = {
            idx = i,
            sx = sx, sy = sy, sw = sw, sh = sh,
            wx = wx, wy = wy, ww = ww, wh = wh,
            isPrimary = isPrimary,
            dpi = 96,
            effScaleX = 1.0,
            effScaleY = 1.0
        }
        list[#list + 1] = mon
        if isPrimary then primaryRm = mon end
    end

    if #list == 0 then
        local fallback = {
            idx = 1,
            sx = primSX, sy = primSY, sw = primSW, sh = primSH,
            wx = primWX, wy = primWY, ww = primWW, wh = primWH,
            isPrimary = true,
            dpi = 96,
            effScaleX = 1.0,
            effScaleY = 1.0
        }
        list[1] = fallback
        primaryRm = fallback
    elseif not primaryRm then
        primaryRm = list[1]
        primaryRm.isPrimary = true
    end

    -- Enrich each live Rainmeter monitor with true per-monitor DPI scaling from MonitorMetrics.lua
    local mm = monitorMetrics
    if mm and type(mm.monitors) == 'table' and #mm.monitors == #list then
        local physMons = mm.monitors
        local primaryPhys = nil
        for _, pm in ipairs(physMons) do
            if pm.isPrimary then primaryPhys = pm; break end
        end
        if not primaryPhys then primaryPhys = physMons[1] end

        local primaryDpi = (mm.primaryDpi and mm.primaryDpi > 0) and mm.primaryDpi or (primaryPhys.dpi or 96)
        local awareness = mm.rainmeterDpiAwareness
        if awareness == nil or awareness < 0 then
            -- Infer Rainmeter's active DPI awareness from primary monitor ratio
            if primaryPhys.sw and primaryPhys.sw > 0 then
                local pRatio = primaryRm.sw / primaryPhys.sw
                if primaryDpi > 96 and abs(pRatio - (96 / primaryDpi)) <= 0.04 then
                    awareness = 0 -- DPI unaware
                else
                    awareness = 1 -- System DPI aware
                end
            else
                awareness = 1
            end
        end

        local usedPhys = {}
        local matched = {}

        -- Match primary monitor first
        for pIdx, pm in ipairs(physMons) do
            if pm == primaryPhys then
                usedPhys[pIdx] = true
                matched[primaryRm.idx] = pm
                break
            end
        end

        -- Match remaining monitors by exact geometry, aspect ratio, and relative screen quadrant
        for _, rm in ipairs(list) do
            if not matched[rm.idx] then
                local bestIdx = nil
                local bestScore = 1e18
                local rmAspect = rm.sw / rm.sh
                local rmDirX = Sign(rm.sx - primaryRm.sx)
                local rmDirY = Sign(rm.sy - primaryRm.sy)

                for pIdx, pm in ipairs(physMons) do
                    if not usedPhys[pIdx] and pm.sw and pm.sh and pm.sw > 0 and pm.sh > 0 then
                        local score = 0
                        if rm.sx == pm.sx and rm.sy == pm.sy and rm.sw == pm.sw and rm.sh == pm.sh then
                            score = -1000
                        else
                            local pmAspect = pm.sw / pm.sh
                            score = abs(rmAspect - pmAspect) * 100
                            if Sign(pm.sx - primaryPhys.sx) ~= rmDirX then score = score + 50 end
                            if Sign(pm.sy - primaryPhys.sy) ~= rmDirY then score = score + 50 end
                            local rmRelX = (rm.sx - primaryRm.sx) / max(1, primaryRm.sw)
                            local pmRelX = (pm.sx - primaryPhys.sx) / max(1, primaryPhys.sw)
                            local rmRelY = (rm.sy - primaryRm.sy) / max(1, primaryRm.sh)
                            local pmRelY = (pm.sy - primaryPhys.sy) / max(1, primaryPhys.sh)
                            score = score + (abs(rmRelX - pmRelX) + abs(rmRelY - pmRelY)) * 10
                            -- Prefer monitors whose width ratio matches a valid DPI scale ratio
                            local wRatio = rm.sw / pm.sw
                            local minRatioErr = min(
                                abs(wRatio - 1.0),
                                abs(wRatio - (96 / (pm.dpi or 96))),
                                abs(wRatio - (primaryDpi / (pm.dpi or 96)))
                            )
                            score = score + minRatioErr * 40
                        end
                        if score < bestScore then
                            bestScore = score
                            bestIdx = pIdx
                        end
                    end
                end

                if bestIdx then
                    usedPhys[bestIdx] = true
                    matched[rm.idx] = physMons[bestIdx]
                end
            end
        end

        -- Compute exact skin-pixel to Rainmeter-work-area coordinate scale per monitor:
        --   effScale = dwmWindowScale * (rmScreenSize / physScreenSize)
        for _, rm in ipairs(list) do
            local pm = matched[rm.idx]
            if pm and pm.sw and pm.sh and pm.sw > 0 and pm.sh > 0 then
                local monDpi = (pm.dpi and pm.dpi > 0) and pm.dpi or 96
                rm.dpi = monDpi
                local dwmScale = 1.0
                if awareness == 0 then
                    dwmScale = monDpi / 96.0
                elseif awareness == 1 then
                    dwmScale = monDpi / primaryDpi
                else
                    dwmScale = 1.0 -- Per-monitor DPI aware: no DWM bitmap scaling
                end
                rm.effScaleX = SnapScale(dwmScale * (rm.sw / pm.sw))
                rm.effScaleY = SnapScale(dwmScale * (rm.sh / pm.sh))
            end
        end
    end

    return list
end

local function ResolveMonitorForFolder(origX, origY, monitors)
    if origX == nil or origY == nil then
        return monitors[1]
    end

    -- Pass 1: Strict half-open work-area containment of visible folder icon center
    for _, m in ipairs(monitors) do
        local ax = origX + (ICON_CENTER_X * m.effScaleX)
        local ay = origY + (ICON_CENTER_Y * m.effScaleY)
        if ax >= m.wx and ax < (m.wx + m.ww) and ay >= m.wy and ay < (m.wy + m.wh) then
            return m
        end
    end

    -- Pass 2: Strict half-open full screen-area containment (catches folders near/over taskbar)
    for _, m in ipairs(monitors) do
        local ax = origX + (ICON_CENTER_X * m.effScaleX)
        local ay = origY + (ICON_CENTER_Y * m.effScaleY)
        if ax >= m.sx and ax < (m.sx + m.sw) and ay >= m.sy and ay < (m.sy + m.sh) then
            return m
        end
    end

    -- Pass 3: Nearest monitor by squared Euclidean distance (never snaps to primary by accident)
    local best = monitors[1]
    local bestDistSq = 1e30
    for _, m in ipairs(monitors) do
        local ax = origX + (ICON_CENTER_X * m.effScaleX)
        local ay = origY + (ICON_CENTER_Y * m.effScaleY)
        local cx = min(max(ax, m.sx), m.sx + m.sw)
        local cy = min(max(ay, m.sy), m.sy + m.sh)
        local dx = ax - cx
        local dy = ay - cy
        local distSq = (dx * dx) + (dy * dy)
        if distSq < bestDistSq then
            bestDistSq = distSq
            best = m
        end
    end
    return best
end

local function GetSharedSeams(activeMon, monitors)
    local seamL, seamR, seamT, seamB = false, false, false, false
    local aL, aR = activeMon.sx, activeMon.sx + activeMon.sw
    local aT, aB = activeMon.sy, activeMon.sy + activeMon.sh

    for _, other in ipairs(monitors) do
        if other ~= activeMon then
            local oL, oR = other.sx, other.sx + other.sw
            local oT, oB = other.sy, other.sy + other.sh
            local overlapY = (min(aB, oB) - max(aT, oT)) > 0
            local overlapX = (min(aR, oR) - max(aL, oL)) > 0

            if overlapY and abs(oR - aL) <= 10 then seamL = true end
            if overlapY and abs(oL - aR) <= 10 then seamR = true end
            if overlapX and abs(oB - aT) <= 10 then seamT = true end
            if overlapX and abs(oT - aB) <= 10 then seamB = true end
        end
    end
    return seamL, seamR, seamT, seamB
end

local function GetAnimationOverhang(style, panelW, panelH)
    -- Base 2px for [PanelBackground] Padding=2,2,2,2
    local overL, overR, overT, overB = 2, 2, 2, 2
    if style == 'ElasticBounce' then
        -- Peak scale ~1.057x
        local extraW = ceil(panelW * 0.058)
        local extraH = ceil(panelH * 0.058)
        overL = overL + extraW
        overR = overR + extraW
        overT = overT + extraH
        overB = overB + extraH
    elseif style == 'Settle' then
        -- Starts at 1.06x centered -> 3% per side
        local extraW = ceil(panelW * 0.032)
        local extraH = ceil(panelH * 0.032)
        overL = overL + extraW
        overR = overR + extraW
        overT = overT + extraH
        overB = overB + extraH
    elseif style == 'VerticalBounce' then
        -- Peak vertical bounce overshoot ~4.2px + margin
        overT = overT + 8
        overB = overB + 8
    end
    return overL, overR, overT, overB
end

function OpenPanel()
    if isOpen and animState ~= "closing" then return end
    if selectedIdx >= 0 then
        RestoreIcon(selectedIdx)
        selectedIdx = -1
    end

    cachedStyle = (SKIN:GetVariable('AnimStyle') or 'ExpandCollapse'):gsub('%s+', '')

    local skinX = tonumber(SKIN:ReplaceVariables('#CURRENTCONFIGX#'))
    local skinY = tonumber(SKIN:ReplaceVariables('#CURRENTCONFIGY#'))

    if pendingRestore then
        pendingRestore = false
        skinX = savedOrigX or skinX
        skinY = savedOrigY or skinY
    end

    if not isOpen then
        savedOrigX = skinX
        savedOrigY = skinY
        didMove = false
    end

    local monitors = EnumerateRainmeterMonitors()
    local activeMon = ResolveMonitorForFolder(savedOrigX, savedOrigY, monitors)
    local workX, workY = activeMon.wx, activeMon.wy
    local rightEdge = workX + activeMon.ww
    local bottomEdge = workY + activeMon.wh
    local effScaleX = activeMon.effScaleX
    local effScaleY = activeMon.effScaleY
    local dpiScale = (activeMon.dpi or 96) / 96.0

    local seamL, seamR, seamT, seamB = GetSharedSeams(activeMon, monitors)
    local baseMargin = max(6, floor(6 * dpiScale + 0.5))
    local seamGuard = ceil(dpiScale * 2)
    local marginL = baseMargin + (seamL and seamGuard or 0)
    local marginR = baseMargin + (seamR and seamGuard or 0)
    local marginT = baseMargin + (seamT and seamGuard or 0)
    local marginB = baseMargin + (seamB and seamGuard or 0)

    local overL, overR, overT, overB = GetAnimationOverhang(cachedStyle, cachedPanelW, cachedPanelH)

    isOpen = true
    local newSkinX = savedOrigX
    local newSkinY = savedOrigY
    local iconOffsetX = 0
    local iconOffsetY = 0
    local panelX = DEFAULT_PANEL_X
    local panelY = DEFAULT_PANEL_Y

    openLeft = false
    openUp = false

    if savedOrigX ~= nil and savedOrigY ~= nil then
        -- Footprint of popup and animation overhang in Rainmeter's monitor coordinate space
        local popupW_s = cachedPanelW * effScaleX
        local popupH_s = cachedPanelH * effScaleY
        local overL_s = overL * effScaleX
        local overR_s = overR * effScaleX
        local overT_s = overT * effScaleY
        local overB_s = overB * effScaleY

        local minPopupX_s = workX + marginL + overL_s
        local maxPopupX_s = rightEdge - marginR - popupW_s - overR_s
        if maxPopupX_s < minPopupX_s then maxPopupX_s = minPopupX_s end

        local minPopupY_s = workY + marginT + overT_s
        local maxPopupY_s = bottomEdge - marginB - popupH_s - overB_s
        if maxPopupY_s < minPopupY_s then maxPopupY_s = minPopupY_s end

        -- Horizontal edge resolution (both right and left monitor boundaries)
        local defaultPopupX_s = savedOrigX + (DEFAULT_PANEL_X * effScaleX)
        local desiredPopupX_s = defaultPopupX_s
        if defaultPopupX_s > maxPopupX_s then
            openLeft = true
            desiredPopupX_s = savedOrigX + ((ICON_RIGHT_EDGE - cachedPanelW) * effScaleX)
            desiredPopupX_s = max(minPopupX_s, min(desiredPopupX_s, maxPopupX_s))
        elseif defaultPopupX_s < minPopupX_s then
            desiredPopupX_s = minPopupX_s
        end

        -- Vertical edge resolution (both bottom/taskbar and top monitor boundaries)
        local defaultPopupY_s = savedOrigY + (DEFAULT_PANEL_Y * effScaleY)
        local desiredPopupY_s = defaultPopupY_s
        if defaultPopupY_s > maxPopupY_s then
            openUp = true
            desiredPopupY_s = savedOrigY + ((ICON_TOP_GAP_Y - cachedPanelH) * effScaleY)
            desiredPopupY_s = max(minPopupY_s, min(desiredPopupY_s, maxPopupY_s))
        elseif defaultPopupY_s < minPopupY_s then
            desiredPopupY_s = minPopupY_s
        end

        -- Solve (newSkinX, iconOffsetX, panelX) keeping iconOffsetX >= 0 and icon pixel-locked
        local minLocalPanelX = max(DEFAULT_PANEL_X, overL + 4)
        local candSkinX = floor(desiredPopupX_s - (minLocalPanelX * effScaleX) + 0.5)
        if candSkinX < savedOrigX then
            iconOffsetX = ceil((savedOrigX - candSkinX) / effScaleX)
            newSkinX = floor(savedOrigX - (iconOffsetX * effScaleX) + 0.5)
            panelX = max(minLocalPanelX, floor((desiredPopupX_s - newSkinX) / effScaleX + 0.5))
        else
            newSkinX = savedOrigX
            iconOffsetX = 0
            panelX = max(minLocalPanelX, floor((desiredPopupX_s - newSkinX) / effScaleX + 0.5))
        end

        -- Solve (newSkinY, iconOffsetY, panelY) keeping iconOffsetY >= 0 and icon pixel-locked
        local minLocalPanelY = max(10, overT + 4)
        if openUp then
            local candSkinY = floor(desiredPopupY_s - (minLocalPanelY * effScaleY) + 0.5)
            if candSkinY < savedOrigY then
                iconOffsetY = ceil((savedOrigY - candSkinY) / effScaleY)
                newSkinY = floor(savedOrigY - (iconOffsetY * effScaleY) + 0.5)
                panelY = max(minLocalPanelY, floor((desiredPopupY_s - newSkinY) / effScaleY + 0.5))
            else
                newSkinY = savedOrigY
                iconOffsetY = 0
                panelY = max(minLocalPanelY, floor((desiredPopupY_s - newSkinY) / effScaleY + 0.5))
            end
        else
            newSkinY = savedOrigY
            iconOffsetY = 0
            panelY = max(DEFAULT_PANEL_Y, floor((desiredPopupY_s - newSkinY) / effScaleY + 0.5))
        end

        -- Precompute skin-local monitor clamp limits for zero-overhead per-frame animation clamping
        cachedMinLocalX = max(2, ceil((workX + marginL - newSkinX) / effScaleX))
        cachedMaxLocalRight = floor((rightEdge - marginR - newSkinX) / effScaleX)
        cachedMinLocalY = max(2, ceil((workY + marginT - newSkinY) / effScaleY))
        cachedMaxLocalBottom = floor((bottomEdge - marginB - newSkinY) / effScaleY)
    else
        cachedMinLocalX = 2
        cachedMaxLocalRight = 99999
        cachedMinLocalY = 2
        cachedMaxLocalBottom = 99999
    end

    cachedPanelX = panelX
    cachedPanelY = panelY

    local setupBang =
        '[!SetVariable IsOpen 1]' ..
        '[!KeepOnScreen 0][!Draggable 0]' ..
        '[!SetVariable IconOffsetX ' .. iconOffsetX .. ']' ..
        '[!SetVariable IconOffsetY ' .. iconOffsetY .. ']' ..
        '[!SetVariable PanelX ' .. panelX .. ']' ..
        '[!SetVariable PanelY ' .. panelY .. ']' ..
        '[!ShowMeterGroup PanelContent][!HideMeter SelectionHighlight][!HideMeter HoverHighlight]'

    local moveBang = ''
    if newSkinX ~= nil and newSkinY ~= nil and (newSkinX ~= skinX or newSkinY ~= skinY) then
        didMove = true
        moveBang = '[!Move ' .. newSkinX .. ' ' .. newSkinY .. ']'
    end

    lastScale, lastAlpha, lastShiftX, lastShiftY, lastMatrix = -1, -1, -9999, -9999, ''

    if cachedStyle == 'None' then
        animState = "idle"
        animProgress = 1
        SKIN:Bang(setupBang .. '[!ShowMeterGroup PanelHitboxes]')
        ApplyAnimFrame(1, true)
        SKIN:Bang('[!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle][!UpdateMeter *][!Redraw]' .. moveBang)
    else
        animState = "opening"
        animStartProgress = (animProgress > 0 and animProgress < 1) and animProgress or 0.12
        animProgress = animStartProgress
        animStartTime = clock()
        SKIN:Bang(setupBang .. '[!HideMeterGroup PanelHitboxes]')
        ApplyAnimFrame(animProgress, true)
        SKIN:Bang('[!SetOption MeasureToggle UpdateDivider 1][!UpdateMeasure MeasureToggle][!UpdateMeter *][!Redraw]' .. moveBang)
    end
end

function ClosePanel()
    if not isOpen or animState == "closing" then return end
    if selectedIdx >= 0 then
        RestoreIcon(selectedIdx)
        selectedIdx = -1
    end

    cachedStyle = (SKIN:GetVariable('AnimStyle') or 'ExpandCollapse'):gsub('%s+', '')

    if cachedStyle == 'None' then
        FinishClose()
    else
        hoveredIdx = -1
        hoverAlpha = 0
        hoverTarget = 0
        lastHoverAlpha = 0
        animState = "closing"
        animStartProgress = (animProgress > 0) and animProgress or 1
        animStartTime = clock()
        SKIN:Bang(
            '[!HideMeterGroup PanelHitboxes][!HideMeter SelectionHighlight][!HideMeter HoverHighlight]' ..
            '[!SetVariable HoverAlpha 0][!UpdateMeter HoverHighlight]' ..
            '[!SetOption MeasureToggle UpdateDivider 1][!UpdateMeasure MeasureToggle]'
        )
    end
end

function FinishClose(immediate)
    isOpen = false
    animState = "idle"
    animProgress = 0
    hoveredIdx = -1
    hoverAlpha = 0
    hoverTarget = 0
    lastHoverAlpha = 0
    cachedPanelX = DEFAULT_PANEL_X
    cachedPanelY = DEFAULT_PANEL_Y
    cachedMinLocalX = 2
    cachedMaxLocalRight = 99999
    cachedMinLocalY = 2
    cachedMaxLocalBottom = 99999
    lastScale, lastAlpha, lastShiftX, lastShiftY, lastMatrix = 1, 0, 0, 0, '1;0;0;1;0;0'

    local curX = tonumber(SKIN:ReplaceVariables('#CURRENTCONFIGX#'))
    local curY = tonumber(SKIN:ReplaceVariables('#CURRENTCONFIGY#'))
    local needsMove = (savedOrigX ~= nil and savedOrigY ~= nil) and (didMove or curX ~= savedOrigX or curY ~= savedOrigY)

    local resetBang =
        '[!HideMeterGroup PanelContent][!HideMeterGroup PanelHitboxes][!HideMeter SelectionHighlight][!HideMeter HoverHighlight]' ..
        '[!SetVariable IsOpen 0][!SetVariable HoverAlpha 0]' ..
        '[!SetVariable AnimScale 1][!SetVariable AnimAlpha 0]' ..
        '[!SetVariable AnimShiftX 0][!SetVariable AnimShiftY 0]' ..
        '[!SetVariable PanelMatrix "1;0;0;1;0;0"]' ..
        '[!SetVariable IconOffsetX 0][!SetVariable IconOffsetY 0]' ..
        '[!SetVariable PanelX ' .. DEFAULT_PANEL_X .. '][!SetVariable PanelY ' .. DEFAULT_PANEL_Y .. ']' ..
        '[!KeepOnScreen 0][!UpdateMeter *][!Redraw]'

    if needsMove and not immediate then
        pendingRestore = true
        SKIN:Bang(resetBang .. '[!SetOption MeasureToggle UpdateDivider 1][!UpdateMeasure MeasureToggle]')
    else
        pendingRestore = false
        didMove = false
        SKIN:Bang('[!SetOption MeasureToggle UpdateDivider -1][!UpdateMeasure MeasureToggle]' .. resetBang)
        if needsMove then
            SKIN:Bang('[!KeepOnScreen 0][!Move ' .. savedOrigX .. ' ' .. savedOrigY .. '][!Redraw]')
        end
        SKIN:Bang('[!Draggable 1]')
    end
end

function ClosePanelInstant()
    if selectedIdx >= 0 then
        RestoreIcon(selectedIdx)
        selectedIdx = -1
    end
    if isOpen then
        FinishClose(true)
    else
        pendingRestore = false
        didMove = false
        hoveredIdx = -1
        hoverAlpha = 0
        hoverTarget = 0
        lastHoverAlpha = 0
        SKIN:Bang('[!Draggable 1][!KeepOnScreen 0]')
    end
end
